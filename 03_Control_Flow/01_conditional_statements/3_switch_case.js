let grade = "C";

switch(grade){

    case "A":
        console.log("Excellent");
        break;

      
    case "B":
        console.log("Good");
        break;

        
    case "C":
        console.log("Average");    
        break;

    default:
        console.log("Fail");
        break;    
     
}



